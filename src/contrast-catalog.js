export function getContrastById(id) {
  return CONTRAST_CATALOG[id] || null;
}

function getSoundContrastKey(contrast) {
  return contrast
    .split(/\s+vs\s+/u)
    .map((sound) => sound.trim())
    .sort()
    .join(' vs ');
}

export function getRelatedContrasts(contrastId, { limit = 3 } = {}) {
  const contrast = getContrastById(contrastId);

  if (!contrast) {
    return [];
  }

  const soundContrastKey = getSoundContrastKey(contrast.contrast);

  return Object.values(CONTRAST_CATALOG)
    .filter((candidate) => (
      candidate.id !== contrast.id
      && getSoundContrastKey(candidate.contrast) === soundContrastKey
    ))
    .sort((first, second) => first.id.localeCompare(second.id))
    .slice(0, limit);
}

export function getContrastIdFromWords(words = []) {
  return words.map((word) => word.text.toLowerCase()).join('-vs-');
}

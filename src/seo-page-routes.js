const SEO_PAGE_SLUG_SET = new Set(SEO_PAGE_SLUGS);

export function getPublishedSeoPairRoute({ pairId, locale = 'en' } = {}) {
  if (!pairId || !locale) {
    return null;
  }

  const routeSlug = locale === 'en' ? pairId : `${locale}/${pairId}`;
  return SEO_PAGE_SLUG_SET.has(routeSlug) ? `/${routeSlug}/` : null;
}
